_last: dict[tuple[str, str], str] = {}


class _Safe(dict):
    def __missing__(self, key):        # ไม่ส่งค่ามาก็ไม่พัง
        return ""


def say(game: str, event: str, *, chance: float = 1.0, rng: Optional[random.Random] = None, **fmt) -> Optional[str]:
    """เลือกประโยคตอบโต้ของเหตุการณ์นี้ (หรือ None ถ้าปิดอยู่/ไม่ถึงตาที่จะพูด/ไม่มีเหตุการณ์นี้)"""
    pool = POOLS.get(game, {}).get(event)
    if not ENABLED or not pool:
        return None
    rng = rng or random
    if rng.random() >= min(1.0, chance * CHANCE_SCALE):
        return None
    key = (game, event)
    options = [t for t in pool if t != _last.get(key)] or pool
    text = rng.choice(options)
    _last[key] = text
    return text.format_map(_Safe(fmt)).strip()


def tag(text: Optional[str]) -> str:
    """ต่อท้ายข้อความเกมเป็นบรรทัดใหม่ (ว่างถ้าไม่มีอะไรจะพูด)"""
    return f"\n💬 **{BOT_NAME}:** {text}" if text else ""
