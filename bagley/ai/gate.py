# ค่าเริ่มต้น: ถ้ากรองแล้วเหลือน้อยเกินไปจะไม่ใช้ shortlist (ส่งทั้งหมดเหมือนเดิม)
MAX_SHORTLIST = 22

_ALL_KEYWORDS = sorted({k for v in COMMAND_KEYWORDS.values() for k in v}, key=len, reverse=True)
_ALL_RE = re.compile("|".join(re.escape(k) for k in _ALL_KEYWORDS), re.I)
_URL_RE = re.compile(r"https?://|www\.", re.I)


def looks_like_command(text: str) -> bool:
    """True ถ้าข้อความมีคำที่บ่งบอกการสั่งงาน/ลิงก์ — ถ้า False ให้ข้าม AI Router ไปคุยเล่นเลย"""
    if not text:
        return False
    t = text.lower()
    return bool(_URL_RE.search(t) or _ALL_RE.search(t))


def shortlist(text: str, command_names) -> list:
    """คืนชื่อคำสั่งที่เกี่ยวข้องกับข้อความ (เรียงตามจำนวนคำที่ตรง) เหลือว่าง = ใช้ทั้งหมด"""
    t = (text or "").lower()
    names = set(command_names)
    scored = []
    for cmd, kws in COMMAND_KEYWORDS.items():
        if cmd not in names:
            continue
        s = sum(len(k) for k in kws if k.lower() in t)
        if s:
            scored.append((s, cmd))
    # ชื่อคำสั่งที่พิมพ์ตรงๆ เช่น "/skip" "play"
    for n in names:
        if n.lower() in t and all(n != c for _, c in scored) and len(n) >= 4:
            scored.append((len(n), n))
    scored.sort(reverse=True)
    out = [c for _, c in scored][:MAX_SHORTLIST]
    if _URL_RE.search(t):
        for extra in ("play", "watch_live_chat", "toggle_live_chat"):
            if extra in names and extra not in out:
                out.append(extra)
    return out


def needs_confirm(cmd_name: str) -> bool:
    return cmd_name in NEEDS_CONFIRM
